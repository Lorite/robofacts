        "An entry of [[checklist-json|preflight_checklist.json]] names a check by its script name without `.sh` and passes its arguments as `key=value` pairs. "
        "The gate looks for the script in this order: the project's own `common/preflight/checks/` under the experiments root, "
        "the enabled [[robot-adapters|robot adapters]], the project's backend, and last the general checks. "
