# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
PAGES = {
    "commands.md": commands_page,
    "lint-rules.md": lint_rules_page,
    "gate-checks.md": gate_checks_page,
}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing: exit 1 and name each page that differs from what the code gives")
    args = ap.parse_args(argv)
    this = sys.version_info[:2]
    other_python = not HELP_PYTHON <= this <= HELP_PYTHON_SAME_UNTIL
    stale = []
    for name, build in PAGES.items():
        target = PAGES_DIR / name
        if name == "commands.md" and other_python:
            if args.check:
                print(f"skipped {target.relative_to(REPO)}: Python {this[0]}.{this[1]} formats help "
                      f"differently, check it with Python {HELP_PYTHON[0]}.{HELP_PYTHON[1]}")
                continue
            print(f"warning: Python {this[0]}.{this[1]} formats help differently from Python "
                  f"{HELP_PYTHON[0]}.{HELP_PYTHON[1]}, which CI checks {target.relative_to(REPO)} with",
                  file=sys.stderr)
        text = build()
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if args.check:
            if current != text:
                stale.append(target)
        elif current != text:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(REPO)}")
    if stale:
        for target in stale:
            print(f"stale: {target.relative_to(REPO)} (run python3 tools/gen_docs_reference.py)", file=sys.stderr)
        return 1
    if args.check:
        print("the generated reference pages are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
