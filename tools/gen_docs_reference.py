# The gate checks page
# --------------------------------------------------------------------------- #
GENERAL_CHECKS = CORE_SRC / "robofacts" / "preflight" / "checks"
ROS2_CHECKS = ROS2_SRC / "robofacts_ros2" / "checks"


def check_header(script: Path) -> Tuple[str, List[str]]:
    """What a check script verifies (the first sentence of its header comment) and its
    usage lines (the lines that start with the script's name), without the name."""
    comment: List[str] = []
    for line in script.read_text(encoding="utf-8").splitlines()[1:]:
        if not line.startswith("#"):
            break
        comment.append(line[1:].strip())
    first_paragraph = []
    for line in comment:
        if not line:
            break
        first_paragraph.append(line)
    # The first block of usage lines. Later ones are examples.
    usages: List[str] = []
    for line in comment:
        if line.startswith(f"{script.name} ") or line == script.name:
            usages.append(line[len(script.name):].strip())
        elif usages and line.startswith("["):
            usages[-1] += " " + line   # a usage that goes on in the next comment line
        elif usages:
            break
    return first_sentence(" ".join(first_paragraph)), usages


def _check_rows(directory: Path, parallel: frozenset, sequential: Dict[str, str],
                aliases: Dict[str, str]) -> List[Tuple[str, ...]]:
    rows = []
    for script in sorted(directory.glob("*.sh")):
        name = script.stem
        verifies, usages = check_header(script)
        second = sorted(a for a, target in aliases.items() if target == name)
        shown = f"`{name}`" + "".join(f"<br>(also `{a}`)" for a in second)
        concurrency = ("parallel-safe" if name in parallel else
                       "sequential" if name in sequential else "not classified (runs alone)")
        arguments = " or ".join(code(u) if u else "none" for u in usages) or "none"
        rows.append((shown, cell(verifies), arguments, concurrency))
    return rows


def _alone(directory: Path, sequential: Dict[str, str]) -> List[str]:
    names = sorted(s.stem for s in directory.glob("*.sh") if s.stem in sequential)
    return [f"- `{name}`: {prose(_without_history(sequential[name]))}." for name in names]


