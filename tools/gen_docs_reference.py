#!/usr/bin/env python3
"""Write the three reference pages of the documentation site that come from the code.

    docs/reference/commands.md     every ``trials`` command with its help text, from the
                                   argparse parsers, the general ones and the ROS 2 backend's
    docs/reference/lint-rules.md   every lint rule with its id and what it checks, from
                                   robofacts/robofacts/lint.py and robofacts_ros2/robofacts_ros2/lint_ros2.py
    docs/reference/gate-checks.md  every packaged gate check with what it verifies, its
                                   arguments and its concurrency class

Usage:

    python3 tools/gen_docs_reference.py           write the three pages
    python3 tools/gen_docs_reference.py --check   change nothing, exit 1 and name each stale page

The script documents the checkout it lives in: it imports both packages from their source
folders, needs no ROS 2 installation and starts nothing. It needs PyYAML, as the packages do.
The output is deterministic: the help texts are formatted at a fixed width, and every list
comes from the code in a fixed order.

argparse formats help a little differently from one Python version to another: Python 3.13
prints an option with two names and a value as ``-o, --opt VALUE``. Write the pages with Python
3.10, the Python of ROS 2 Humble, where CI checks them. Python 3.11 and 3.12 write the same
commands page. From Python 3.13 on, ``--check`` skips the commands page and says so.

A text from the code that the docs style does not allow in prose (a semicolon, an en or em
dash, a date) goes into a code span, so the package's own texts stay as they are. A remark in
parentheses that starts with a date is the history of a rule, not its content, and is left out:
``(levels that bind a gate, 2026-10-01, a paper)`` becomes ``(levels that bind a gate)``.
"""
from __future__ import annotations

import argparse
import ast
import contextlib
import io
import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

REPO = Path(__file__).resolve().parents[1]
CORE_SRC = REPO / "robofacts"
ROS2_SRC = REPO / "robofacts_ros2"
PAGES_DIR = REPO / "docs" / "reference"

#: The Python that writes the commands page, and the newest one that formats help the same
#: way (see the module docstring).
HELP_PYTHON = (3, 10)
HELP_PYTHON_SAME_UNTIL = (3, 12)
#: The terminal width argparse formats the help texts for.
HELP_COLUMNS = 90

#: The backends whose commands the commands page lists: the general view first.
GENERAL_BACKEND = "process"
ROS2_BACKEND = "ros2"

REGENERATE = "<!-- Generated by tools/gen_docs_reference.py from the code. Do not edit by hand: run python3 tools/gen_docs_reference.py -->"

DATE = re.compile(r"\b20\d\d-\d\d-\d\d\b")
#: What the docs style does not allow in prose: a semicolon, an en dash, an em dash, a date.
NOT_IN_PROSE = re.compile(r"[;–—]|\b20\d\d-\d\d-\d\d\b")
SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9(`\"\[])")
RULE_ID = re.compile(r"^(L\d+b?)\b")


# --------------------------------------------------------------------------- #
# Text helpers
# --------------------------------------------------------------------------- #
def _without_history(text: str) -> str:
    """``text`` without the dates in its parentheses, and without what follows each date
    there: ``(a, 2026-10-01, a paper)`` becomes ``(a)``, and ``(2026-10-06)`` goes away."""
    def keep_before_date(match: re.Match) -> str:
        space, inner = match.group(1), match.group(2)
        if not DATE.search(inner):
            return match.group(0)
        items = inner.split(", ")
        kept = items[:next(i for i, item in enumerate(items) if DATE.search(item))]
        return f"{space}({', '.join(kept)})" if kept else ""
    return re.sub(r"(\s*)\(([^()]*)\)", keep_before_date, text).strip()


def _one_line(text: str) -> str:
    return " ".join(text.split())


def first_sentence(text: str) -> str:
    """The first sentence of a paragraph, on one line and without its history remarks."""
    text = _without_history(_one_line(text))
    return SENTENCE_END.split(text, maxsplit=1)[0].strip()


CODE_SPAN = re.compile(r"(`[^`]*`)")


def prose(text: str, in_table: bool = False) -> str:
    """A text from the code as Markdown, on one line. It goes into a code span when, outside
    its own code spans, it holds what prose may not, or a ``<`` (``<uid>`` would read as an
    HTML tag, and its escape ``&lt;`` holds a semicolon). Otherwise ``*`` is escaped, and so
    is ``|`` in a table. A pipe inside a code span needs no escape."""
    text = _one_line(text)
    outside = CODE_SPAN.sub("", text)
    if NOT_IN_PROSE.search(outside) or "<" in outside:
        return code(text)
    parts = CODE_SPAN.split(text)
    for i in range(0, len(parts), 2):   # the parts outside the code spans
        parts[i] = parts[i].replace("*", "\\*")
        if in_table:
            parts[i] = parts[i].replace("|", "\\|")
    return "".join(parts)


def cell(text: str) -> str:
    """A table cell from a text of the code (see prose)."""
    return prose(text, in_table=True)


def code(text: str) -> str:
    """A code span, for a table cell or for prose."""
    return "`" + _one_line(text).replace("`", "") + "`"


def table(header: Tuple[str, ...], rows: List[Tuple[str, ...]]) -> List[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def page(title: str, body: List[str]) -> str:
    """A whole page: the title, the line that says how to write it again, then ``body``."""
    text = "\n".join([f"# {title}", "", REGENERATE, "", *body])
    return re.sub(r"\n{3,}", "\n\n", text).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# The commands page
# --------------------------------------------------------------------------- #
def _import_packages() -> None:
    """Import both packages from this checkout, never from an installed copy."""
    for src in (ROS2_SRC, CORE_SRC):
        if str(src) in sys.path:
            sys.path.remove(str(src))
        sys.path.insert(0, str(src))


def _help_text(name: str) -> str:
    """What ``trials <name> --help`` prints, with trailing spaces removed."""
    from robofacts import cli
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
        try:
            code_ = cli.main([name, "--help"])
        except SystemExit as exc:
            code_ = exc.code
    if code_ not in (0, None):
        raise RuntimeError(f"trials {name} --help exited with {code_}")
    return "\n".join(line.rstrip() for line in out.getvalue().strip("\n").splitlines())


def _commands_of(backend_name: str) -> Dict[str, Tuple[str, str]]:
    """``{name: (one-line help, --help text)}`` of every command of a project on ``backend_name``,
    read from an empty directory, so no project around the working directory counts."""
    from robofacts import cli
    saved_env = {k: os.environ.get(k) for k in ("TRIALS_BACKEND", "COLUMNS", "NO_COLOR",
                                                 "TRIALS_EXPERIMENTS_ROOT", "TRIALS_PROJECT_ROOT")}
    saved_cwd = os.getcwd()
    with tempfile.TemporaryDirectory() as empty:
        try:
            os.chdir(empty)
            os.environ.update({"TRIALS_BACKEND": backend_name, "COLUMNS": str(HELP_COLUMNS), "NO_COLOR": "1"})
            os.environ.pop("TRIALS_EXPERIMENTS_ROOT", None)
            os.environ.pop("TRIALS_PROJECT_ROOT", None)
            return {name: (summary, _help_text(name)) for name, (_, summary) in cli.commands().items()}
        finally:
            os.chdir(saved_cwd)
            for key, value in saved_env.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value


def _command_section(heading: str, note: Optional[str], help_text: str) -> List[str]:
    lines = [f"### {heading}", ""]
    if note:
        lines += [note, ""]
    return lines + ["```text", help_text, "```", ""]


def commands_page() -> str:
    _import_packages()
    from robofacts import backend
    general = _commands_of(GENERAL_BACKEND)
    ros2 = _commands_of(ROS2_BACKEND)
    ros2_own = backend.load(ROS2_BACKEND).commands
    added = [n for n in ros2 if n not in general]
    changed = [n for n in ros2 if n in general and ros2[n][1] != general[n][1]]

    def slug(heading: str) -> str:
        return "#" + re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")

    body = [
        "This page lists every `trials` command with the help text that `trials <command> --help` prints. "
        "A script writes the page from the command parsers, so it matches the code of this version.",
        "",
        "Each command answers `--help`, and `trials --help` lists them all. "
        "A [[backends|backend]] may add commands of its own or replace a general one. "
        "The section [With the ROS 2 backend](#with-the-ros-2-backend) lists what the ROS 2 backend changes.",
        "",
        "## General commands",
        "",
        "These commands exist in every project, whatever its backend.",
        "",
        *table(("Command", "What it does"),
               [(f"[`trials {n}`]({slug('trials ' + n)})", cell(general[n][0])) for n in general]),
        "",
    ]
    for name, (_, help_text) in general.items():
        body += _command_section(f"trials {name}", None, help_text)

    ros2_heading = {n: (f"trials {n}" if n in added else f"trials {n} with the ROS 2 backend")
                    for n in [*added, *changed]}
    body += [
        "## With the ROS 2 backend",
        "",
        "A project whose `trials.yaml` says `backend: ros2` has these commands in addition to the general ones, "
        "or in place of them.",
        "",
        *table(("Command", "Change", "What it does"),
               [(f"[`trials {n}`]({slug(ros2_heading[n])})",
                 "added" if n in added else ("replaced" if n in ros2_own else "same command, other help"),
                 cell(ros2[n][0])) for n in [*added, *changed]]),
        "",
    ]
    for name in added:
        body += _command_section(ros2_heading[name], "The ROS 2 backend adds this command.", ros2[name][1])
    for name in changed:
        note = ("The ROS 2 backend replaces the general command." if name in ros2_own else
                "The command is the general one. Its help differs with the ROS 2 backend.")
        body += _command_section(ros2_heading[name], note, ros2[name][1])
    return page("Commands", body)


# --------------------------------------------------------------------------- #
# The lint rules page
# --------------------------------------------------------------------------- #
LINT_FILES = (CORE_SRC / "robofacts" / "lint.py", ROS2_SRC / "robofacts_ros2" / "lint_ros2.py")


def _rule_key(rule: str) -> Tuple[int, str]:
    match = re.fullmatch(r"L(\d+)(\w*)", rule)
    return int(match.group(1)), match.group(2)


def lint_rules(path: Path) -> List[Tuple[str, str, List[str]]]:
    """``(id, what it checks, test functions)`` of every rule of a lint file, read with ast:
    the rule list of the module docstring and the ids that start the tests' docstrings."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    entries: Dict[str, List[str]] = {}
    current: Optional[str] = None
    for line in (ast.get_docstring(tree, clean=True) or "").splitlines():
        match = re.match(r"^(L\d+b?)\s+(.*)$", line)
        if match:
            current = match.group(1)
            entries[current] = [match.group(2)]
        elif current and line.startswith((" ", "\t")):
            entries[current].append(line.strip())
        else:
            current = None
    tests: Dict[str, List[str]] = {}
    summaries: Dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            doc = ast.get_docstring(node) or ""
            match = RULE_ID.match(doc)
            if not match:
                raise SystemExit(f"{path.name}: {node.name} names no rule id (L<n>) at the start of its docstring")
            tests.setdefault(match.group(1), []).append(node.name)
            summaries.setdefault(match.group(1), re.sub(r"^\S+\s*[-–—:]?\s*", "", doc.split("\n\n")[0]))
    rules = []
    for rule in sorted(set(entries) | set(tests), key=_rule_key):
        text = first_sentence(" ".join(entries[rule])) if rule in entries else first_sentence(summaries[rule])
        rules.append((rule, text, tests.get(rule, [])))
    return rules


def _count(rules: List[Tuple[str, str, List[str]]]) -> str:
    """``12 rules and the part L4b``: numbered rules, then the second parts of a rule."""
    parts = [rule for rule, _, _ in rules if not re.fullmatch(r"L\d+", rule)]
    text = f"{len(rules) - len(parts)} rules"
    return text + (f" and the {'part' if len(parts) == 1 else 'parts'} {', '.join(parts)}" if parts else "")


def lint_rules_page() -> str:
    general, ros2 = (lint_rules(path) for path in LINT_FILES)

    def rows(rules):
        return [(f"`{rule}`", cell(text), "<br>".join(f"`{t}`" for t in tests) or "none")
                for rule, text, tests in rules]

    body = [
        "This page lists the rules that `trials lint` checks in the declarations of every experiment. "
        "A script writes the page from the rule lists in the code, so it matches the code of this version.",
        "",
        "## How the lint runs",
        "",
        "Each rule is one or more pytest tests. `trials lint` runs the general rules first and then the rules of the project's [[backends|backend]]. "
        "`trials lint --experiment <name>` lints one experiment, and the rules over shared files still run. "
        "Other flags go to pytest, so `trials lint -k <test name>` runs the tests of one rule. "
        "`trials validate` runs the lint as one of its stages.",
        "",
        "A rule id is `L` and a number. `L4b` is a second part of `L4`. "
        "The numbers are shared by both lists, so the ROS 2 rules fill the gaps in the general list.",
        "",
        "## General rules",
        "",
        "These rules run for every project, from `robofacts/robofacts/lint.py`.",
        "",
        *table(("Rule", "What it checks", "Test"), rows(general)),
        "",
        "## Rules of the ROS 2 backend",
        "",
        "These rules are facts about ROS 2. They run after the general rules for a project whose backend is `ros2`, "
        "from `robofacts_ros2/robofacts_ros2/lint_ros2.py`.",
        "",
        *table(("Rule", "What it checks", "Test"), rows(ros2)),
        "",
        "## Counts",
        "",
        f"The general list has {_count(general)}. The ROS 2 list has {_count(ros2)}. "
        f"Together they hold {len(general) + len(ros2)} rule ids and {sum(len(t) for _, _, t in general + ros2)} tests.",
    ]
    return page("Lint rules", body)


